#!/usr/bin/env python3
"""Generate THIRD_PARTY_NOTICES.md for EZPy2STL.

Walks the dependency tree rooted at the runtime dependencies in
pyproject.toml (plus PyInstaller, which builds the .app), using the packages
installed in the CURRENT environment, and writes each package's name,
version, licence and full licence/notice text.

Run it in the environment you build the .app from, so it matches uv.lock:

    uv sync --extra build
    uv run python tools/generate_notices.py

Re-run it whenever dependencies change, then commit the result.
"""
import re
import sys
import tomllib
from importlib import metadata
from pathlib import Path

from packaging.requirements import Requirement
from packaging.utils import canonicalize_name

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "THIRD_PARTY_NOTICES.md"
# The .app is macOS-only, so evaluate environment markers as macOS.
ENV = {"sys_platform": "darwin", "platform_system": "Darwin",
       "os_name": "posix", "platform_machine": "arm64"}
EXTRA_ROOTS = ["pyinstaller"]            # bundled bootloader ships in the .app
LICENSE_FILE = re.compile(r"(licen[sc]e|copying|notice|authors)", re.I)


def project_requirements():
    data = tomllib.loads((ROOT / "pyproject.toml").read_text())
    return list(data["project"]["dependencies"]) + EXTRA_ROOTS


def closure(roots):
    seen, todo = {}, [Requirement(r) for r in roots]
    while todo:
        req = todo.pop()
        name = canonicalize_name(req.name)
        try:
            dist = metadata.distribution(name)
        except metadata.PackageNotFoundError:
            print(f"warning: {name} not installed here, skipped", file=sys.stderr)
            continue
        entry = seen.setdefault(name, {"dist": dist, "extras": set()})
        new_extras = set(req.extras) - entry["extras"]
        if entry["extras"] and not new_extras and name in seen and entry.get("done"):
            continue
        entry["extras"] |= set(req.extras)
        if entry.get("done") and not new_extras:
            continue
        entry["done"] = True
        for r in dist.requires or []:
            child = Requirement(r)
            if child.marker is None:
                todo.append(child)
                continue
            for extra in (entry["extras"] or {""}):
                if child.marker.evaluate({**ENV, "extra": extra}):
                    todo.append(child)
                    break
    return seen


def licence_label(md):
    expr = md.get("License-Expression")
    if expr:
        return expr
    cls = [c.split("::")[-1].strip() for c in md.get_all("Classifier") or []
           if c.startswith("License ::")]
    cls = [c for c in cls if c != "OSI Approved"]
    lic = (md.get("License") or "").strip()
    if cls:
        return "; ".join(cls)
    return lic if lic and len(lic) < 80 and "\n" not in lic else (
        "see licence text below" if lic else "UNKNOWN - check manually")


def licence_texts(dist):
    out = []
    for f in dist.files or []:
        if LICENSE_FILE.search(f.name) and ".dist-info" in str(f) or \
           LICENSE_FILE.search(f.name) and ".egg-info" in str(f):
            try:
                text = dist.locate_file(f).read_text(errors="replace").strip()
            except OSError:
                continue
            if text:
                out.append((f.name, text))
    if not out:
        lic = (dist.metadata.get("License") or "").strip()
        if len(lic) >= 80 or "\n" in lic:
            out.append(("License (from package metadata)", lic))
    return out


def vendored_lines():
    """Licence texts for the front-end libraries copied into
    frontend/vendor/ (Three.js, CodeMirror, fonts) -- not Python packages,
    so the dependency walk above can't see them."""
    vendor = ROOT / "frontend" / "vendor"
    lines = ["", "## Bundled front-end libraries", "",
             "Copied into `frontend/vendor/` (versions in "
             "`frontend/vendor/README.md`).", ""]
    for lic in sorted(vendor.glob("*/LICENSE*")):
        text = lic.read_text(errors="replace").strip()
        lines += [f"### {lic.parent.name}", "",
                  f"<details><summary>{lic.name}</summary>", "", "```", text, "```", "",
                  "</details>", ""]
    return lines


def main():
    pkgs = closure(project_requirements())
    lines = [
        "# Third-party notices", "",
        "EZPy2STL is licensed under GPL-2.0-or-later (see `LICENSE`). The "
        "standalone `.app` bundles the open-source packages below, each under "
        "its own licence. Generated by `tools/generate_notices.py`; do not edit "
        "by hand.", "",
        "PyInstaller's bootloader is GPL-2.0-or-later *with an exception* that "
        "permits distributing the frozen app under any licence.", "",
        f"{len(pkgs)} packages.", "", "## Summary", "",
        "| Package | Version | Licence |", "|---|---|---|"]
    rows = sorted(pkgs.values(), key=lambda e: e["dist"].metadata["Name"].lower())
    for e in rows:
        md = e["dist"].metadata
        lines.append(f"| {md['Name']} | {e['dist'].version} | {licence_label(md).replace('|', '/')} |")
    lines += ["", "## Full texts", ""]
    for e in rows:
        d, md = e["dist"], e["dist"].metadata
        lines += [f"### {md['Name']} {d.version}", "",
                  f"Licence: {licence_label(md)}"]
        url = md.get("Home-page") or next(
            (u.split(",", 1)[-1].strip() for u in md.get_all("Project-URL") or []), "")
        if url:
            lines.append(f"Project: {url}")
        lines.append("")
        for fname, text in licence_texts(d):
            lines += [f"<details><summary>{fname}</summary>", "", "```", text, "```", "",
                      "</details>", ""]
    lines += vendored_lines()
    OUT.write_text("\n".join(lines))
    unknown = [e["dist"].metadata["Name"] for e in rows
               if "UNKNOWN" in licence_label(e["dist"].metadata)]
    print(f"wrote {OUT} ({len(pkgs)} packages)")
    if unknown:
        print("licence not detected for:", ", ".join(unknown))


if __name__ == "__main__":
    main()
